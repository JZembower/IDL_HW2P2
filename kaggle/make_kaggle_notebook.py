def course_utils_cell():
    files = {}
    for name in ("__init__.py", "metrics_calculator.py", "submission_utils.py"):
        with open(os.path.join(UTILS, name), encoding="utf-8") as f:
            files[name] = f.read()
    body = ",\n".join(f"    {name!r}: {src!r}" for name, src in files.items())
    return ("# Offline copy of https://github.com/CMU-IDeeL/HW2P2-Student-Utils (utils/), unmodified.\n"
            "# Used only when git clone fails (Internet off).\n"
            f"COURSE_UTILS = {{\n{body},\n}}")


def main():
    code = ["".join(c["source"]) for c in json.load(open(NB, encoding="utf-8"))["cells"] if c["cell_type"] == "code"]
    cells = [md(INTRO), cell(SETUP)]
    for marker, heading in CELLS:
        hits = [c for c in code if marker in c]
        assert len(hits) == 1, f"{marker!r} matched {len(hits)} cells"
        src = hits[0]
        assert "\n!" not in "\n" + src, f"cell {marker!r} has a shell (!) line"
        for m, old, new in REPLACE:
            if m == marker:
                assert src.count(old) == 1, f"replacement in {marker!r} matched {src.count(old)} times: {old[:60]!r}"
                src = src.replace(old, new)
        if heading:
            cells.append(md(heading))
        if marker == "run_cls_inference_file_order(":
            cells.append(course_utils_cell())
        cells.append(cell(src))
        cells.extend(AFTER.get(marker, []))

    nb = {
        "cells": [c if isinstance(c, dict) else
                  {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": c}
                  for c in cells],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
            # No "kaggle" block: Kaggle wants numeric source ids there, and a slug makes it retry "adding data source" forever.
            # Data, accelerator and Internet are set by hand in the editor (see the first cell).
        },
        "nbformat": 4,
        "nbformat_minor": 4,
    }
    # Jupyter stores sources as lists of lines
    for c in nb["cells"]:
        c["source"] = c["source"].splitlines(keepends=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(nb, f, indent=1, ensure_ascii=False)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
