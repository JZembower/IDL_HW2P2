"""
Build psc/train.py from the notebook's code cells, so the batch job runs exactly the notebook's code.
Re-run after editing the notebook:  python psc/make_train_script.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NB = os.path.join(ROOT, "F26 HW2P2 Student Starter Notebook_final.ipynb")
OUT = os.path.join(ROOT, "psc", "train.py")

# Notebook cells to include, in order, identified by a unique snippet of each cell
CELLS = [
    "DEVICE = 'cuda' if",                  # Imports
    "'data_root':",                        # Config
    "def create_transforms",               # Augmentations
    "train_transforms = create_transforms",
    "class ImageDataset",                  # Classification data
    "cls_train_dataset = ImageDataset",
    "class ImagePairDataset",              # Verification data
    "ver_val_dataset  = ImagePairDataset",
    "class Network(nn.Module)",            # Model
    "criterion = ArcFaceLoss",             # Loss / optimizer / scheduler
    "class AverageMeter",                  # Metrics
    "def train_epoch(",
    "def valid_epoch_cls(",
    "def valid_epoch_ver(",
    "wandb.login(",
    "run = wandb.init(",
    "def save_model(",                     # Checkpointing
    "best_combined_score = 0.0",           # Training loop
    "run_cls_inference_file_order(",       # Inference + submission CSVs (no Kaggle submit)
]

HEADER = '''"""
Batch-job version of the HW2P2 notebook (generated by psc/make_train_script.py; edit the notebook, not this file).
Downloads the data to the job's $LOCAL disk, trains with resume, writes the submission CSVs.
It does not submit to Kaggle.
With SMOKE=1 it runs a few-minute end-to-end check instead: 1 epoch on a data slice, folder checkpoints/smoke_test, no wandb.
"""
import os
import subprocess
import sys

SMOKE = os.environ.get("SMOKE") == "1"
if SMOKE:
    os.environ["WANDB_MODE"] = "disabled"

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))  # repo/home dir holding .env and checkpoints/
sys.path.insert(0, os.getcwd())  # so `from utils import ...` finds the course utils next to the notebook

ENV = {k.strip(): v.strip().strip('"\\'') for k, v in (l.split('=', 1) for l in open('.env') if '=' in l and not l.lstrip().startswith('#'))}
os.environ['KAGGLE_USERNAME'] = ENV['KAGGLE_USERNAME']
os.environ['KAGGLE_API_TOKEN'] = ENV['KAGGLE_API_KEY']
import kaggle
api = kaggle.api

# Data goes to the node-local disk ($LOCAL is wiped when the job ends, so each job downloads again)
if not os.path.isdir(os.path.join(os.environ["LOCAL"], "hw2p2_data")):
    api.competition_download_files('hw-2-p-2-fall-2026-student-competition', path=os.environ["LOCAL"])
    zip_path = os.path.join(os.environ["LOCAL"], "hw-2-p-2-fall-2026-student-competition.zip")
    subprocess.run(["unzip", "-qo", zip_path, "-d", os.environ["LOCAL"]], check=True)
    os.remove(zip_path)
print("Data:", os.listdir(os.path.join(os.environ["LOCAL"], "hw2p2_data")), flush=True)
'''


# Code inserted right after a cell (by its marker) for SMOKE=1 runs
SMOKE_AFTER = {
    "'data_root':": """if SMOKE:  # separate folder, 1 epoch, never resumes the real run
    config.update(run_name='smoke_test', epochs=1, warmup_epochs=1, margin_warmup_epochs=1, resume=False)
    config['checkpoint_dir'] = os.path.join("./checkpoints", config['run_name'])
    os.makedirs(config['checkpoint_dir'], exist_ok=True)
""",
    "cls_train_dataset = ImageDataset": """if SMOKE:  # 1/200 of train, 1/20 of dev
    from torch.utils.data import Subset
    cls_train_loader = DataLoader(Subset(cls_train_dataset, range(0, len(cls_train_dataset), 200)), shuffle=True, drop_last=True, **loader_kwargs)
    cls_val_loader = DataLoader(Subset(cls_val_dataset, range(0, len(cls_val_dataset), 20)), shuffle=False, **loader_kwargs)
""",
}


def main():
    code = ["".join(c["source"]) for c in json.load(open(NB, encoding="utf-8"))["cells"] if c["cell_type"] == "code"]
    parts = [HEADER]
    for marker in CELLS:
        hits = [c for c in code if marker in c]
        assert len(hits) == 1, f"{marker!r} matched {len(hits)} cells"
        src = hits[0]
        assert "\n!" not in "\n" + src, f"cell {marker!r} has a shell (!) line"
        parts.append(f"# ---- notebook cell: {marker.strip()} ----\n{src.rstrip()}\n")
        if marker in SMOKE_AFTER:
            parts.append(SMOKE_AFTER[marker])
    parts.append('if SMOKE:\n    os.remove("submission.csv")  # the smoke copy must never be mistaken for a real submission\n    print("SMOKE TEST PASSED", flush=True)\n')
    parts.append('print("Done. Submission files are in", config["checkpoint_dir"], flush=True)\n')
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n\n".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
